-- -------------------------------------------------------------
-- ACCESO DE CLIENTE FINAL A SUS PROPIOS DATOS (políticas adicionales,
-- no reemplazan las de "Estudios can manage..." de arriba)
-- -------------------------------------------------------------
-- Función SECURITY DEFINER: rompe la recursión circular entre "empresas" y
-- "clientes_finales" (la política de empresas necesita consultar
-- clientes_finales, y la de clientes_finales necesita consultar empresas —
-- si ambas se evalúan bajo RLS normal, Postgres entra en loop infinito,
-- error 42P17 "infinite recursion detected in policy"). Al ser
-- SECURITY DEFINER, esta consulta interna a clientes_finales corre sin
-- pasar por su propia RLS, cortando el ciclo.
CREATE OR REPLACE FUNCTION public.is_cliente_of_empresa(check_empresa_id TEXT)
RETURNS BOOLEAN AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.clientes_finales
        WHERE clientes_finales.id = auth.uid()
          AND clientes_finales.empresa_id = check_empresa_id
    );
$$ LANGUAGE sql SECURITY DEFINER STABLE SET search_path = public, pg_temp;

CREATE POLICY "Cliente final ve su propia empresa"
    ON public.empresas FOR SELECT TO authenticated
    USING (public.is_cliente_of_empresa(empresas.id));

CREATE POLICY "Cliente final ve sus propios comprobantes"
    ON public.comprobantes_digitales FOR SELECT TO authenticated
    USING (public.is_cliente_of_empresa(comprobantes_digitales.empresa_id));

CREATE POLICY "Cliente final sube sus propios comprobantes"
    ON public.comprobantes_digitales FOR INSERT TO authenticated
    WITH CHECK (
        public.is_cliente_of_empresa(comprobantes_digitales.empresa_id)
        AND estado = 'Recibido' -- el cliente no puede autoaprobar; el estudio lo procesa
    );


-- ---------------------------------------------------------------------
-- 🛡️ FUNCIONES DE SEGURIDAD Y TRIGGERS DE VALIDACIÓN IMPOSTIVA (CPN AUDIT)
-- ---------------------------------------------------------------------

-- A. Función para validar CUITs de AFIP (Algoritmo Modulo 11 oficial)
CREATE OR REPLACE FUNCTION public.validar_cuit_afip(cuit_input TEXT)
RETURNS BOOLEAN AS $$
DECLARE
    cuit_clean TEXT;
    cuit_array INT[];
    verificador INT;
    acumulado INT := 0;
    multiplicadores INT[] := ARRAY[5, 4, 3, 2, 7, 6, 5, 4, 3, 2];
    i INT;
    calculado INT;
BEGIN
    -- Limpiar guiones o espacios
    cuit_clean := regexp_replace(cuit_input, '[^0-9]', '', 'g');

    -- Si es consumidor final sin registrar o CUIT extranjero simplificado
    IF cuit_clean = '00000000000' OR cuit_clean = '' OR cuit_clean IS NULL THEN
        RETURN TRUE;
    END IF;

    -- Validar longitud exacta de 11 dígitos
    IF length(cuit_clean) != 11 THEN
        RETURN FALSE;
    END IF;

    -- Extraer dígitos a un array
    FOR i IN 1..11 LOOP
        cuit_array[i] := cast(substring(cuit_clean from i for 1) AS INT);
    END LOOP;

    verificador := cuit_array[11];

    -- Aplicar algoritmo módulo 11
    FOR i IN 1..10 LOOP
        acumulado := acumulado + (cuit_array[i] * multiplicadores[i]);
    END LOOP;

    calculado := 11 - (acumulado % 11);

    IF calculado = 11 THEN
        calculado := 0;
    ELSIF calculado = 10 THEN
        calculado := 9;
    END IF;

    RETURN calculado = verificador;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;


-- B. Trigger para validar CUITs al insertar/modificar empresas y transacciones
CREATE OR REPLACE FUNCTION public.trigger_cuit_validation()
RETURNS TRIGGER AS $$
BEGIN
    IF NOT public.validar_cuit_afip(NEW.cuit) THEN
        -- Registrar intento de carga erróneo en auditoría
        INSERT INTO public.seguridad_logs (estudio_id, evento, tabla, registro_id, detalles)
        VALUES (
            COALESCE(auth.uid(), '00000000-0000-0000-0000-000000000000'::uuid),
            'RECHAZO_CUIT_INVALIDO',
            TG_TABLE_NAME::TEXT,
            NEW.id::TEXT,
            -- to_jsonb(NEW)->>'razon_social' es seguro en ambas tablas: esta
            -- función valida CUITs tanto en "empresas" (tiene razon_social)
            -- como en "transacciones" (no la tiene) — un acceso directo
            -- NEW.razon_social rompe con "record has no field" en esta última.
            jsonb_build_object('cuit_invalido', NEW.cuit, 'razon_social', COALESCE(to_jsonb(NEW)->>'razon_social', 'N/A'))
        );
        RAISE EXCEPTION 'Error impositivo AFIP: La CUIT % ingresada posee un dígito verificador inválido bajo Algoritmo Módulo 11.', NEW.cuit;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp;

-- Aplicar validación a empresas y transacciones
CREATE OR REPLACE TRIGGER on_empresa_validate_cuit
    BEFORE INSERT OR UPDATE ON public.empresas
